const fs = require('node:fs'), path = require('node:path'), ts = require('typescript');

/** Read setting labels from their JSX; search stays current in builds and HMR. */
function buildSettingsSearch() {
  const root = path.resolve(__dirname, '..'), folder = path.join(root, 'renderer/pages/settings/sections');
  const entries = [], known = new Set();
  const readKeys = node => {
    const keys = [];
    const visit = child => {
      if (ts.isCallExpression(child) && ['t', 'tk'].includes(child.expression.getText()) && ts.isStringLiteral(child.arguments[0])) keys.push(child.arguments[0].text);
      ts.forEachChild(child, visit);
    };
    if (node) visit(node);
    return keys;
  };
  const readProps = node => Object.fromEntries(node.attributes.properties.filter(ts.isJsxAttribute).map(attr => [attr.name.getText(), readKeys(attr.initializer)]));
  const add = entry => { const id = entry.section + ':' + entry.labelKey; if (!known.has(id)) { known.add(id); entries.push(entry); } };
  const sources = fs.readdirSync(folder).filter(file => /(?:Section|AppearancePanel)\.tsx$/.test(file)).sort().map(file => ({ file: path.join(folder, file), section: file === 'AppearancePanel.tsx' ? 'interface' : file.replace('Section.tsx', '').toLowerCase() }));
  sources.push({ file: path.join(root, 'renderer/components/ExternalPlayerPreferences.tsx'), section: 'general', parentKey: 'external.player', descriptionKey: 'external.saved' });
  for (const { file, section, parentKey: defaultParent, descriptionKey } of sources) {
    const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    const visit = (node, parentKey) => {
      let parent = parentKey;
      const tag = ts.isJsxElement(node) ? node.openingElement : ts.isJsxSelfClosingElement(node) ? node : null;
      if (tag) {
        const props = readProps(tag), name = tag.tagName.getText(source);
        if (name === 'SettingsCard') {
          parent = props.title?.[0];
          for (const labelKey of props.title ?? []) add({ section, labelKey, kind: 'card', ...(props.description?.[0] && { descriptionKey: props.description[0] }) });
        } else if (name === 'SettingRow') {
          for (const labelKey of props.label ?? []) add({ section, labelKey, kind: 'row', ...(props.description?.[0] && { descriptionKey: props.description[0] }), ...(parent && { parentKey: parent }) });
        } else if (props['data-setting-label']?.length || props.ariaLabel?.length || props['aria-label']?.length) {
          for (const labelKey of props['data-setting-label'] ?? props.ariaLabel ?? props['aria-label']) add({ section, labelKey, kind: 'control', ...(descriptionKey && { descriptionKey }), ...(parent && { parentKey: parent }) });
        }
      }
      ts.forEachChild(node, child => visit(child, parent));
    };
    visit(source, defaultParent);
  }
  // Keybindings have dynamic rows; their labels/descriptions are declared together.
  const hotkeysFile = path.join(root, 'renderer/components/HotkeySettings.tsx');
  const hotkeys = ts.createSourceFile(hotkeysFile, fs.readFileSync(hotkeysFile, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const maps = {};
  const readHotkeys = node => {
    if (ts.isVariableDeclaration(node) && ['hotkeyLabels', 'hotkeyDescriptions'].includes(node.name.getText(hotkeys)) && ts.isObjectLiteralExpression(node.initializer)) {
      maps[node.name.getText(hotkeys)] = Object.fromEntries(node.initializer.properties.filter(ts.isPropertyAssignment).map(p => [p.name.text, readKeys(p.initializer)[0]]));
    }
    ts.forEachChild(node, readHotkeys);
  };
  readHotkeys(hotkeys);
  for (const [id, labelKey] of Object.entries(maps.hotkeyLabels ?? {})) add({ section: 'hotkeys', labelKey, descriptionKey: maps.hotkeyDescriptions?.[id], parentKey: 'hotkeys.title', kind: 'row' });
  const result = '// Generated by scripts/build-settings-search.cjs from setting labels.\nimport type { SettingSearchEntry } from \'./settingsSearch\';\n\nexport const SETTINGS_SEARCH_ENTRIES: readonly SettingSearchEntry[] = ' + ('[\n' + entries.map(entry => '  ' + JSON.stringify(entry)).join(',\n') + '\n]') + ';\n';
  const target = path.join(folder, '../settingsSearchCatalog.ts');
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== result) fs.writeFileSync(target, result);
  return entries.length;
}
module.exports = buildSettingsSearch;
if (require.main === module) console.log('Indexed settings:', buildSettingsSearch());
