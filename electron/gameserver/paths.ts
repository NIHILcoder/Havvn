// Import staging
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Where user-supplied server files are unpacked BEFORE an instance exists.
 *
 * A sibling of the instances rather than the OS temp dir, for two reasons that
 * both come down to the same move: committing an import is a `rename`, and rename
 * is only atomic within a filesystem. Staging in %TEMP% on a machine whose
 * userData is on another drive turns "commit the import" into a multi-gigabyte
 * copy that can fail halfway. The leading dot keeps it out of the instance id
 * pattern, so a staging directory can never be mistaken for an instance.
 */
export function importStagingRoot(): string {
  return path.join(serversRoot(), '.import');
}

export function importStagingDir(stagingId: string): string {
  if (!isValidInstanceId(stagingId)) throw new Error(`invalid stagingId: ${String(stagingId)}`);
  return path.join(importStagingRoot(), stagingId);
}

/**
 * Delete every staged import. Called at startup and at shutdown: a staging
 * directory only has meaning inside one create-server dialog, so anything found
 * at boot is the debris of a crash and holding gigabytes for it helps nobody.
 */
export function purgeImportStaging(): void {
  fs.rmSync(importStagingRoot(), { recursive: true, force: true });
}

/**
 * Every file under `dir`, as instance-root-relative '/' paths.
 *
 * Bounded on purpose. A modpack with 40 000 files is real, a zip bomb with four
 * million is also real, and the caller uses this listing to answer a question
 * that the first few thousand entries already answer. `truncated` is returned
 * rather than swallowed so the UI can say the scan was partial.
 */
export function listTree(dir: string, limit = 50_000): { files: RelPath[]; bytes: number; truncated: boolean } {
  const files: RelPath[] = [];
  let bytes = 0;
  let truncated = false;

  const walk = (abs: string, rel: string): void => {
    if (truncated) return;
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(abs, { withFileTypes: true });
    } catch {
      return; // unreadable subtree — not fatal to identifying the server
    }
    for (const entry of entries) {
      if (files.length >= limit) { truncated = true; return; }
      const childRel = rel ? `${rel}/${entry.name}` : entry.name;
      // Never follow links: an archive can contain one, and a scan that walks it
      // would report files from outside the staging directory as if they were
      // part of the import.
      if (entry.isSymbolicLink()) continue;
      if (entry.isDirectory()) {
        walk(path.join(abs, entry.name), childRel);
      } else if (entry.isFile()) {
        files.push(childRel);
        try { bytes += fs.statSync(path.join(abs, entry.name)).size; } catch { /* raced */ }
      }
    }
  };

  walk(dir, '');
  return { files, bytes, truncated };
}
